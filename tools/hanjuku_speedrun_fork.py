def _git_env() -> dict:
    """Return an environment usable for git.

    Some harnesses export ``GIT_CONFIG_COUNT`` without the matching
    ``GIT_CONFIG_KEY_n`` variables.  Git treats that as a hard configuration
    error, so drop the malformed trio rather than failing every git call.
    """
    env = dict(os.environ)
    raw = env.get('GIT_CONFIG_COUNT')
    if raw is None:
        return env
    try:
        count = int(raw)
    except ValueError:
        count = -1
    if count < 0 or any(f'GIT_CONFIG_KEY_{i}' not in env for i in range(count)):
        env.pop('GIT_CONFIG_COUNT', None)
        for key in list(env):
            if key.startswith('GIT_CONFIG_KEY_') or key.startswith('GIT_CONFIG_VALUE_'):
                env.pop(key, None)
    return env


def _git(args: list[str], *, cwd: Path) -> bytes:
    proc = subprocess.run(
        ['git', '--no-pager', *args],
        cwd=str(cwd),
        env=_git_env(),
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        check=False,
    )
    if proc.returncode != 0:
        detail = proc.stderr.decode('utf-8', 'replace').strip()
        raise ToolError(f'git {" ".join(args)} failed: {detail or "unknown error"}')
    return proc.stdout


def _find_repo_root(explicit: str | None) -> Path:
    if explicit:
        return Path(explicit).resolve()
    try:
        top = _git(['rev-parse', '--show-toplevel'], cwd=Path.cwd())
        text = top.decode('utf-8', 'replace').strip()
        if text:
            return Path(text).resolve()
    except ToolError:
        pass
    return Path(__file__).resolve().parents[1]


def _resolve_commit(ref: str, repo: Path) -> str:
    out = _git(['rev-parse', '--verify', f'{ref}^{{commit}}'], cwd=repo)
    sha = out.decode('ascii', 'replace').strip()
    if not re.fullmatch(r'[0-9a-f]{40,64}', sha):
        raise ToolError(f'cannot resolve source ref {ref!r} to a commit')
    return sha


def _list_tree(sha: str, repo: Path) -> list[str]:
    out = _git(['ls-tree', '-r', '-z', '--name-only', sha], cwd=repo)
    return sorted(p.decode('utf-8') for p in out.split(b'\0') if p)


def _read_blob(sha: str, path: str, repo: Path) -> bytes:
    return _git(['show', f'{sha}:{path}'], cwd=repo)


