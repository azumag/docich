class _Source:
    """Character-offset view of a source file.

    ``ast`` reports UTF-8 byte column offsets; the file may contain Japanese
    text, so conversions have to use the encoded prefix.
    """

    def __init__(self, text: str):
        self.text = text
        self.lines = text.splitlines(keepends=True)
        self.line_starts: list[int] = []
        offset = 0
        for line in self.lines:
            self.line_starts.append(offset)
            offset += len(line)

    def _char_col(self, lineno: int, byte_col: int) -> int:
        line = self.lines[lineno - 1]
        return len(line.encode('utf-8')[:byte_col].decode('utf-8', 'replace'))

    def pos(self, lineno: int, byte_col: int) -> int:
        return self.line_starts[lineno - 1] + self._char_col(lineno, byte_col)

    def segment(self, node: ast.AST) -> str:
        start = self.pos(node.lineno, node.col_offset)
        end = self.pos(node.end_lineno, node.end_col_offset)
        return self.text[start:end]

    def line_prefix(self, node: ast.AST) -> str:
        line = self.lines[node.lineno - 1]
        return line[:self._char_col(node.lineno, node.col_offset)]


@dataclass(frozen=True)
class _Edit:
    start: int
    end: int
    text: str


def _apply_edits(source: str, edits: list[_Edit]) -> str:
    ordered = sorted(edits, key=lambda edit: (edit.start, edit.end))
    previous_end = -1
    for edit in ordered:
        if edit.start < previous_end:
            raise ToolError('internal error: overlapping source edits')
        previous_end = max(previous_end, edit.end)
    result = source
    for edit in reversed(ordered):
        result = result[:edit.start] + edit.text + result[edit.end:]
    return result


def _apply_name_rules(value: str, *, test_mode: bool = False) -> str:
    value = _GAME_RE.sub(GAME_SPEEDRUN, value)
    for old, new in SHARED_FILE_RENAMES.items():
        value = value.replace(old, new)
    if test_mode:
        # Copied tests load the copied command brain, not the original one.
        value = value.replace('brains/hanjuku/', 'brains/hanjuku_speedrun/')
    return value


def _module_lookup(module: str, module_map: dict[str, str]) -> str | None:
    """Resolve a module name, accepting the ``src.``-prefixed spelling too."""
    target = module_map.get(module)
    if target is not None:
        return target
    if module.startswith('src.'):
        target = module_map.get(module[len('src.'):])
        if target is not None:
            return 'src.' + target
    return None


def _module_reference_target(value: str, module_map: dict[str, str]) -> str | None:
    """Rewrite a module reference at a module boundary.

    ``docich.hanjuku_run.event`` becomes
    ``docich.hanjuku_speedrun.hanjuku_run.event`` while
    ``docich.hanjuku_runner`` is not touched.  Longest source module wins.
    """
    best: str | None = None
    for source in module_map:
        if value == source or value.startswith(source + '.'):
            if best is None or len(source) > len(best):
                best = source
    if best is None:
        return None
    return module_map[best] + value[len(best):]


def _docstring_ids(tree: ast.AST) -> set[int]:
    ids: set[int] = set()
    for node in ast.walk(tree):
        if isinstance(node, (ast.Module, ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
            if not node.body:
                continue
            first = node.body[0]
            if (isinstance(first, ast.Expr)
                    and isinstance(first.value, ast.Constant)
                    and isinstance(first.value.value, str)):
                ids.add(id(first.value))
    return ids


def _fstring_constant_ids(tree: ast.AST) -> set[int]:
    ids: set[int] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.JoinedStr):
            for value in node.values:
                if isinstance(value, ast.Constant) and isinstance(value.value, str):
                    ids.add(id(value))
    return ids


_STRING_LITERAL_RE = re.compile(
    r'^([A-Za-z]*)(\"\"\"|\'\'\'|\"|\')(.*)\2$', re.S,
)


def _string_literal(value: str) -> str:
    """Fallback literal for a string that cannot be edited in place."""
    return repr(value)


def _string_literal_like(segment: str, value: str) -> str:
    """Build ``value`` as a literal using the original quoting when safe."""
    match = _STRING_LITERAL_RE.match(segment)
    if match:
        prefix, quote = match.group(1), match.group(2)
        if '\n' not in value and '\\' not in value and quote not in value:
            return f'{prefix}{quote}{value}{quote}'
    return _string_literal(value)


def _rewrite_strings(
    tree: ast.AST,
    view: _Source,
    path: str,
    edits: list[_Edit],
    diagnostics: list[Diagnostic],
    module_map: dict[str, str],
    *,
    is_test: bool = False,
) -> None:
    docstrings = _docstring_ids(tree)
    fstring_constants = _fstring_constant_ids(tree)
    for node in ast.walk(tree):
        if not isinstance(node, ast.Constant) or not isinstance(node.value, str):
            continue
        if id(node) in docstrings:
            continue

        module_target = _module_reference_target(node.value, module_map)
        if module_target is not None:
            segment = view.segment(node)
            replacement = (module_target if id(node) in fstring_constants
                           else _string_literal_like(segment, module_target))
            edits.append(_Edit(
                view.pos(node.lineno, node.col_offset),
                view.pos(node.end_lineno, node.end_col_offset),
                replacement,
            ))
            continue

        new_value = _apply_name_rules(node.value, test_mode=is_test)
        if new_value == node.value:
            continue
        segment = view.segment(node)
        new_segment = _apply_name_rules(segment, test_mode=is_test)
        if new_segment != segment:
            edits.append(_Edit(
                view.pos(node.lineno, node.col_offset),
                view.pos(node.end_lineno, node.end_col_offset),
                new_segment,
            ))
            continue
        if id(node) in fstring_constants:
            diagnostics.append(Diagnostic(
                path, node.lineno,
                'string content needs an escaped rewrite; f-string segment was not changed',
            ))
            continue
        # The value is split over adjacent literals or uses an escape.  A
        # normal str literal can be replaced as a whole with repr(); the value
        # (not the original quoting) is what the copy has to preserve.
        edits.append(_Edit(
            view.pos(node.lineno, node.col_offset),
            view.pos(node.end_lineno, node.end_col_offset),
            _string_literal(new_value),
        ))


def _call_name(node: ast.AST) -> str | None:
    if isinstance(node, ast.Name):
        return node.id
    if isinstance(node, ast.Attribute):
        base = _call_name(node.value)
        return f'{base}.{node.attr}' if base else None
    return None


def _is_file_path(node: ast.AST) -> bool:
    if isinstance(node, ast.Name):
        return node.id == '__file__'
    if isinstance(node, ast.Call):
        name = _call_name(node.func)
        if name in {'Path', 'pathlib.Path', 'str', 'os.fspath', 'os.path.abspath',
                    'os.path.realpath'}:
            return bool(node.args) and _is_file_path(node.args[0])
        if isinstance(node.func, ast.Attribute) and node.func.attr in {
            'resolve', 'absolute', 'expanduser',
        }:
            return _is_file_path(node.func.value)
        return False
    if isinstance(node, ast.Attribute):
        if node.attr in {'parent', 'parents'}:
            return _is_file_path(node.value)
        return False
    if isinstance(node, ast.Subscript):
        return (
            isinstance(node.value, ast.Attribute)
            and node.value.attr == 'parents'
            and _is_file_path(node.value.value)
        )
    return False


def _parent_count(node: ast.AST) -> int:
    count = 0
    current = node
    while isinstance(current, ast.Attribute) and current.attr == 'parent':
        count += 1
        current = current.value
    return count


def _dirname_depth(node: ast.AST) -> int | None:
    """Number of nested ``os.path.dirname`` calls ending at a file path."""
    if isinstance(node, ast.Call):
        if _call_name(node.func) in {'os.path.dirname', 'dirname'} and len(node.args) == 1:
            inner = _dirname_depth(node.args[0])
            if inner is not None:
                return inner + 1
            if _is_file_path(node.args[0]):
                return 1
            return None
        if _is_file_path(node):
            return 0
    if _is_file_path(node):
        return 0
    return None


def _rewrite_brain_state_dir(
    tree: ast.AST,
    view: _Source,
    path: str,
    edits: list[_Edit],
) -> None:
    """Keep the optional external brain's ``run/brain/hanjuku`` state separate.

    This is a directory rather than one file name, so it cannot be expressed
    in :data:`SHARED_FILE_RENAMES`.  The only source of it in the copied set is
    ``brains/hanjuku/brain.py``; the default speedrun agent is the command bot,
    but a copied brain must not share state if an operator selects it.
    """
    if path != 'brains/hanjuku/brain.py':
        return
    for node in ast.walk(tree):
        if not isinstance(node, ast.BinOp) or not isinstance(node.op, ast.Div):
            continue
        right = node.right
        if not (isinstance(right, ast.Constant)
                and isinstance(right.value, str)
                and right.value == 'hanjuku'):
            continue
        components = []
        current: ast.AST | None = node
        while isinstance(current, ast.BinOp) and isinstance(current.op, ast.Div):
            components.append(current.right)
            current = current.left
        components.append(current)
        values = []
        for part in components:
            if isinstance(part, ast.Constant) and isinstance(part.value, str):
                values.append(part.value)
            elif isinstance(part, ast.Call):
                values.extend(
                    arg.value for arg in part.args
                    if isinstance(arg, ast.Constant) and isinstance(arg.value, str)
                )
        if 'run' in values and 'brain' in values:
            edits.append(_Edit(
                view.pos(right.lineno, right.col_offset),
                view.pos(right.end_lineno, right.end_col_offset),
                _string_literal_like(view.segment(right), 'hanjuku_speedrun'),
            ))


def _rewrite_paths(
    tree: ast.AST,
    view: _Source,
    path: str,
    edits: list[_Edit],
    diagnostics: list[Diagnostic],
    *,
    is_test: bool = False,
) -> None:
    parent_map: dict[int, ast.AST] = {}
    for parent in ast.walk(tree):
        for child in ast.iter_child_nodes(parent):
            parent_map[id(child)] = parent

    for node in ast.walk(tree):
        if isinstance(node, ast.Subscript):
            value = node.value
            if (isinstance(value, ast.Attribute) and value.attr == 'parents'
                    and _is_file_path(value.value)):
                index = node.slice
                if (isinstance(index, ast.Constant) and type(index.value) is int
                        and index.value >= 0):
                    edits.append(_Edit(
                        view.pos(index.lineno, index.col_offset),
                        view.pos(index.end_lineno, index.end_col_offset),
                        str(index.value + 1),
                    ))
                else:
                    diagnostics.append(Diagnostic(
                        path, node.lineno,
                        'Path(__file__).parents[...] has a non-literal or negative index',
                    ))
                continue

        if isinstance(node, ast.Attribute) and node.attr == 'parent' and _is_file_path(node):
            count = _parent_count(node)
            # Copied tests sit one directory deeper, so even a single
            # ``Path(__file__).parent`` (tests/) has to gain a level.  Source
            # files keep the existing rule: a lone ``.parent`` may be the
            # module's own directory and must not move.
            if count < (1 if is_test else 2):
                continue
            parent = parent_map.get(id(node))
            if isinstance(parent, ast.Attribute) and parent.attr == 'parent':
                continue
            end = view.pos(node.end_lineno, node.end_col_offset)
            edits.append(_Edit(end, end, '.parent'))
            continue

        if isinstance(node, ast.Call):
            if _call_name(node.func) not in {'os.path.dirname', 'dirname'}:
                continue
            depth = _dirname_depth(node)
            if depth is None or depth < 2:
                continue
            parent = parent_map.get(id(node))
            if (isinstance(parent, ast.Call)
                    and _call_name(parent.func) in {'os.path.dirname', 'dirname'}
                    and len(parent.args) == 1 and parent.args[0] is node):
                continue
            start = view.pos(node.lineno, node.col_offset)
            end = view.pos(node.end_lineno, node.end_col_offset)
            segment = view.text[start:end]
            edits.append(_Edit(start, end, f'os.path.dirname({segment})'))


def _resolve_relative(module: str | None, level: int, package: str) -> str | None:
    if level == 0:
        return module or ''
    parts = package.split('.') if package else []
    remove = level - 1
    if remove >= len(parts):
        return None
    base = parts[:len(parts) - remove]
    if module:
        base.extend(module.split('.'))
    return '.'.join(base)


def _format_alias(name: str, asname: str | None) -> str:
    return f'{name} as {asname}' if asname else name


def _format_import_from(module: str, names: list[tuple[str, str | None]]) -> str:
    return f'from {module} import ' + ', '.join(_format_alias(*name) for name in names)


def _relative_test_module(module: str, package: str) -> str | None:
    """Return ``module`` relative to ``package``, or ``None`` if it is outside."""
    if module == package:
        return '.'
    prefix = f'{package}.'
    if module.startswith(prefix):
        return f'.{module[len(prefix):]}'
    return None


def _rewrite_import(
    node: ast.Import | ast.ImportFrom,
    package: str,
    module_map: dict[str, str],
    path: str,
    *,
    test_package: str | None = None,
) -> tuple[list[str] | None, str | None]:
    if isinstance(node, ast.Import):
        entries: list[tuple[str, str, list[tuple[str, str | None]]]] = []
        changed = False
        for alias in node.names:
            target = _module_lookup(alias.name, module_map) or alias.name
            if target != alias.name:
                changed = True
            relative = (_relative_test_module(target, test_package)
                        if test_package is not None else None)
            if relative is not None and relative != '.':
                # ``import test_x as alias`` cannot be written relatively;
                # ``from . import test_x as alias`` binds the same module.
                parent, _, leaf = relative.rpartition('.')
                entry = ('from', parent or '.', [(leaf, alias.asname)])
            else:
                entry = ('import', '', [(target, alias.asname)])
            if (entries and entries[-1][0] == entry[0]
                    and entries[-1][1] == entry[1]):
                entries[-1][2].extend(entry[2])
            else:
                entries.append(entry)
        if not changed:
            return None, None
        lines = []
        for kind, module, names in entries:
            if kind == 'from':
                lines.append(_format_import_from(module, names))
            else:
                lines.append('import ' + ', '.join(_format_alias(*name) for name in names))
        return lines, None

    absolute = _resolve_relative(node.module, node.level, package)
    if absolute is None:
        return None, (
            f'relative import level {node.level} goes above the package root'
        )

    def _maybe_relative(module: str) -> str:
        if test_package is None:
            return module
        relative = _relative_test_module(module, test_package)
        return relative if relative is not None else module

    # When the module itself is copied, every imported name lives in the copy.
    absolute_target = _module_lookup(absolute, module_map)
    if absolute_target is not None:
        names = [(alias.name, alias.asname) for alias in node.names]
        return [_format_import_from(_maybe_relative(absolute_target), names)], None

    # Otherwise a name may itself be a copied module (``from docich import
    # hanjuku_run``).  Split only when the target module really differs, and
    # keep the original order for side effects.
    groups: list[tuple[str, list[tuple[str, str | None]]]] = []
    changed = node.level != 0
    for alias in node.names:
        candidate = f'{absolute}.{alias.name}' if absolute else alias.name
        target = _module_lookup(candidate, module_map)
        if target is not None:
            target_module, _, target_name = target.rpartition('.')
            if target_module:
                entry = (_maybe_relative(target_module), [(target_name, alias.asname)])
            else:
                entry = ('', [(target, alias.asname)])
            changed = True
        else:
            entry = (absolute, [(alias.name, alias.asname)])
        if groups and groups[-1][0] == entry[0]:
            groups[-1][1].extend(entry[1])
        else:
            groups.append(entry)

    if not changed:
        return None, None
    lines = []
    for module, names in groups:
        if module:
            lines.append(_format_import_from(module, names))
        else:
            # ``from tests import test_x`` on a package-less tree: bind the
            # module directly instead of producing ``from  import``.
            lines.append('import ' + ', '.join(_format_alias(*name) for name in names))
    return lines, None


# Source patches for dynamic module names that no AST rule can resolve.
# Each entry is (exact source text, replacement, expected occurrences); a
# mismatch is an error, so a change in the original is noticed, not skipped.
SOURCE_PATCHES: dict[str, tuple[tuple[str, str, int], ...]] = {
    # The speedrun bot records a split-timer side effect after ``persist``.
    # Both anchors are matched against the *transformed* copy, so the import
    # already names ``docich.hanjuku_speedrun``.  A missing anchor is an error:
    # a silent skip would ship a bot that never records an attempt.
    'brains/hanjuku/bot.py': (
        ("from docich.hanjuku_speedrun.hanjuku import fault_issue, month_audit, state_budget\n",
         "from docich.hanjuku_speedrun.hanjuku import fault_issue, month_audit, state_budget\n"
         "from docich.hanjuku_speedrun.rta import hook as rta_hook\n", 1),
        ("                        frame_sha256=frame.digest(), frame=frame)),\n",
         "                        frame_sha256=frame.digest(), frame=frame)),\n"
         "                    ('rta_failed', lambda: rta_hook.observe(runtime, records, state, meta, "
         "screenshot=Path(obs['screenshot']))),\n", 1),
    ),
    # Rotating the decision/event logs overwrites ``.previous``.  The speedrun
    # copy hands the outgoing generation to its attempt spool first; the
    # original source is not changed.  The anchor is the exact line in the
    # transformed copy, and the count catches an upstream change.
    'src/docich/hanjuku_run.py': (
        ("        os.replace(path,previous)\n",
         "        try:\n"
         "            from docich.hanjuku_speedrun.rta import spool as _rta_spool\n"
         "            _rta_spool.before_rotate(runtime_dir, name, previous)\n"
         "        except Exception:\n"
         "            pass\n"
         "        os.replace(path,previous)\n", 1),
    ),
    'src/docich/hanjuku_hotload.py': (
        ("importlib.import_module(f'docich.{name}')",
         "importlib.import_module(f'docich.hanjuku_speedrun.{name}')", 1),
        ("package = sys.modules['docich']",
         "package = sys.modules['docich.hanjuku_speedrun']", 1),
        ("full = f'docich.{name}'",
         "full = f'docich.hanjuku_speedrun.{name}'", 1),
    ),
}


#: Files whose patches only make sense when the file really implements the
#: writer being hooked.  Synthetic fixture repositories replace modules with
#: one-line stubs; they are left untouched instead of failing the exact-count
#: check (the real module always has ``append_log`` and is checked normally).
SOURCE_PATCH_GUARDS = {
    'src/docich/hanjuku_run.py': lambda text: 'def append_log(' in text,
}


#: Generated files that must show a patch in the real checkout.  A synthetic
#: fixture repository is allowed to lack them (it has no writer to hook), but
#: the checkout that owns this tool must never ship a copy without it.
REQUIRED_SOURCE_PATCH_MARKERS = {
    'src/docich/hanjuku_speedrun/hanjuku_run.py': 'before_rotate',
}


def _is_real_repository(repo: Path) -> bool:
    """True when ``repo`` is the checkout that contains this tool."""
    try:
        return ((Path(repo) / 'tools' / Path(__file__).name).resolve()
                == Path(__file__).resolve())
    except (OSError, RuntimeError):
        return False


def _verify_required_source_patches(files: dict[str, bytes], *,
                                    require_real: bool) -> None:
    """Fail when the real checkout generated a copy without its patch."""
    if not require_real:
        return
    for path, marker in REQUIRED_SOURCE_PATCH_MARKERS.items():
        data = files.get(path)
        if data is None:
            raise ToolError(
                f'{path}: generated copy is missing; '
                f'the source patch for {marker!r} was not applied')
        if marker not in data.decode('utf-8', 'replace'):
            raise ToolError(
                f'{path}: generated copy is missing {marker!r}; '
                'a source patch was skipped (upstream writer shape changed?)')


def _apply_source_patches(path: str, text: str) -> str:
    guard = SOURCE_PATCH_GUARDS.get(path)
    if guard is not None and not guard(text):
        # The generator's synthetic repositories replace source modules with
        # stubs.  A file that does not own the log writer has no rotation to
        # hook; the real module always does, and then the exact anchors below
        # are enforced.
        return text
    for old, new, count in SOURCE_PATCHES.get(path, ()):
        found = text.count(old)
        if found != count:
            raise ToolError(
                f'{path}: source patch expected {count} occurrence(s) of '
                f'{old!r}, found {found}')
        text = text.replace(old, new)
    return text


def _apply_test_source_patches(path: str, text: str) -> str:
    for old, new, count in TEST_SOURCE_PATCHES.get(path, ()):
        found = text.count(old)
        if found != count:
            raise ToolError(
                f'{path}: test source patch expected {count} occurrence(s) of '
                f'{old!r}, found {found}')
        text = text.replace(old, new)
    return text


def _conftest_body() -> str:
    """The copied suite's conftest: skip only the documented exceptions."""
    lines = [
        '"""Generated skips for the copied hanjuku-speedrun tests."""',
        'from __future__ import annotations',
        '',
        'from pathlib import Path',
        '',
        'import pytest',
        '',
        '',
        'TEST_SKIPS = {',
    ]
    for nodeid in sorted(TEST_SKIPS):
        lines.append(f'    {nodeid!r}: {TEST_SKIPS[nodeid]!r},')
    lines.extend([
        '}',
        '',
        'PACKAGE_DIR = Path(__file__).resolve().parent',
        '',
        '',
        'def pytest_collection_modifyitems(config, items):',
        '    for item in items:',
        '        # This hook runs for the whole session, and the original tests',
        '        # keep the same node id suffix.  Scope the skips to the package',
        '        # (the copy is the key, not the original test of the same name).',
        '        if PACKAGE_DIR not in Path(str(item.path)).resolve().parents:',
        '            continue',
        '        nodeid = item.nodeid.replace("\\\\", "/")',
        '        for key, reason in TEST_SKIPS.items():',
        '            if nodeid == key or nodeid.endswith("/" + key):',
        '                item.add_marker(pytest.mark.skip(reason=reason))',
        '                break',
        '',
    ])
    return '\n'.join(lines)


def _dynamic_module_reviews(tree: ast.AST, path: str) -> list[Diagnostic]:
    reviews = []
    for node in ast.walk(tree):
        if not isinstance(node, ast.JoinedStr):
            continue
        if not any(isinstance(value, ast.FormattedValue) for value in node.values):
            continue
        if any(isinstance(value, ast.Constant)
               and isinstance(value.value, str)
               and 'docich.' in value.value for value in node.values):
            reviews.append(Diagnostic(
                path, node.lineno,
                'dynamic module name (f-string) is left unchanged; rule 2 only '
                'rewrites exact module-name literals',
            ))
    return reviews


