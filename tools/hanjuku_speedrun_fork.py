def _insert_header(text: str, sha: str) -> str:
    marker = HEADER_TEMPLATE.format(sha=sha)
    lines = text.splitlines(keepends=True)
    index = 0
    if index < len(lines) and lines[index].startswith('#!'):
        index += 1
    if index < len(lines) and _ENCODING_RE.match(lines[index]):
        index += 1
    prefix = ''.join(lines[:index])
    rest = ''.join(lines[index:])
    if prefix and not prefix.endswith(('\n', '\r')):
        prefix += '\n'
    return f'{prefix}{marker}\n{rest}'


def _transform_python(path: str, data: bytes, sha: str,
                      module_map: dict[str, str], *,
                      is_test: bool = False) -> tuple[str, list[Diagnostic],
                                                      list[Diagnostic]]:
    try:
        source = data.decode('utf-8')
    except UnicodeDecodeError as exc:
        raise ToolError(f'{path}: source is not UTF-8: {exc}') from exc
    try:
        tree = ast.parse(source, filename=path)
    except SyntaxError as exc:
        raise ToolError(f'{path}: cannot parse source: {exc}') from exc

    view = _Source(source)
    edits: list[_Edit] = []
    diagnostics: list[Diagnostic] = []
    package = _source_package(path)

    for node in ast.walk(tree):
        if not isinstance(node, (ast.Import, ast.ImportFrom)):
            continue
        replacement, reason = _rewrite_import(
            node, package, module_map, path,
            test_package=TEST_PACKAGE if is_test else None,
        )
        if reason is not None:
            diagnostics.append(Diagnostic(path, node.lineno, reason))
            continue
        if replacement is None:
            continue
        prefix = view.line_prefix(node)
        if prefix.strip():
            diagnostics.append(Diagnostic(
                path, node.lineno,
                'import does not start at the beginning of its line',
            ))
            continue
        indent = prefix
        text = ('\n' + indent).join(replacement)
        edits.append(_Edit(
            view.pos(node.lineno, node.col_offset),
            view.pos(node.end_lineno, node.end_col_offset),
            text,
        ))

    _rewrite_strings(tree, view, path, edits, diagnostics, module_map, is_test=is_test)
    _rewrite_brain_state_dir(tree, view, path, edits)
    if not path.startswith('brains/'):
        _rewrite_paths(tree, view, path, edits, diagnostics, is_test=is_test)

    result = _apply_edits(source, edits)
    result = _insert_header(result, sha)
    return result, diagnostics, _dynamic_module_reviews(tree, path)


