def _line_value_comment(line: str) -> tuple[str, str]:
    """Split a TOML ``key = value`` line into value and trailing comment."""
    index = 0
    quote: str | None = None
    escaped = False
    while index < len(line):
        char = line[index]
        if quote:
            if escaped:
                escaped = False
            elif char == '\\' and quote == '"':
                escaped = True
            elif char == quote:
                quote = None
        elif char in {'"', "'"}:
            quote = char
        elif char == '#':
            return line[:index], line[index:]
        index += 1
    return line, ''


def _replace_toml_key(lines: list[str], section: str, key: str, value: str,
                      *, insert_comment: str | None = None) -> list[str]:
    pattern = re.compile(rf'^(\s*{re.escape(key)}\s*=\s*)(.*)$')
    current = None
    changed = False
    out: list[str] = []
    for line in lines:
        header = re.match(r'^\s*\[([^\]]+)\]\s*(?:#.*)?$', line)
        if header:
            current = header.group(1).strip()
            out.append(line)
            continue
        if current == section:
            match = pattern.match(line)
            if match and not changed:
                body, comment = _line_value_comment(match.group(2))
                if insert_comment:
                    out.append(insert_comment + '\n')
                ending = '\n' if line.endswith('\n') else ''
                if line.endswith('\r\n'):
                    ending = '\r\n'
                out.append(f'{match.group(1)}{value}{(" " + comment) if comment else ""}{ending}')
                changed = True
                continue
        out.append(line)
    if not changed:
        raise ToolError(f'{CONFIG_SOURCE}: [{section}] {key} was not found')
    return out


def _transform_config(data: bytes, sha: str) -> bytes:
    try:
        text = data.decode('utf-8')
    except UnicodeDecodeError as exc:
        raise ToolError(f'{CONFIG_SOURCE}: config is not UTF-8: {exc}') from exc
    lines = text.splitlines(keepends=True)
    lines = _replace_toml_key(lines, 'game', 'name', f'"{GAME_SPEEDRUN}"')
    lines = _replace_toml_key(lines, 'game', 'title', '"半熟英雄 スピードラン (SFC)"')
    lines = _replace_toml_key(
        lines, 'agent', 'command',
        '["python3", "brains/hanjuku_speedrun/bot.py"]',
    )
    lines = _replace_toml_key(
        lines, 'hanjuku', 'chart_edition', '"speedrun"',
        insert_comment=CHART_EDITION_COMMENT,
    )
    lines = _replace_toml_key(lines, 'hanjuku.predictions', 'enabled', 'false')
    lines = _replace_toml_key(lines, 'twitch', 'title_prefix', '"[半熟英雄RTA]"')
    result = ''.join(lines)
    if not result.startswith(_MARKER_PREFIX):
        result = HEADER_TEMPLATE.format(sha=sha) + '\n' + result
    return result.encode('utf-8')


