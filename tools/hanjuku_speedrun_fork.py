def _is_top_level_hanjuku(path: str) -> bool:
    pure = PurePosixPath(path)
    return (
        pure.parent == PurePosixPath('src/docich')
        and pure.name.startswith('hanjuku_')
        and pure.suffix == '.py'
    )


def _is_hanjuku_package(path: str) -> bool:
    return path.startswith('src/docich/hanjuku/') and path.endswith('.py')


def _is_brains_hanjuku(path: str) -> bool:
    pure = PurePosixPath(path)
    return pure.parent == PurePosixPath('brains/hanjuku') and pure.suffix == '.py'


def _select_source_paths(paths: list[str]) -> list[str]:
    selected = []
    for path in paths:
        if path == CONFIG_SOURCE:
            selected.append(path)
        elif _is_top_level_hanjuku(path):
            if PurePosixPath(path).stem not in EXCLUDED_MODULES:
                selected.append(path)
        elif _is_hanjuku_package(path):
            selected.append(path)
        elif _is_brains_hanjuku(path):
            selected.append(path)
    return sorted(set(selected))


def _target_path(path: str) -> str:
    if path == CONFIG_SOURCE:
        return CONFIG_TARGET
    pure = PurePosixPath(path)
    if _is_top_level_hanjuku(path):
        return f'src/docich/hanjuku_speedrun/{pure.name}'
    if _is_hanjuku_package(path):
        return 'src/docich/hanjuku_speedrun/hanjuku/' + path[len('src/docich/hanjuku/'):]
    if _is_brains_hanjuku(path):
        return 'brains/hanjuku_speedrun/' + pure.name
    raise ToolError(f'not a source path: {path}')


def _target_module(module: str) -> str | None:
    if module == 'docich.hanjuku':
        return 'docich.hanjuku_speedrun.hanjuku'
    if module.startswith('docich.hanjuku.'):
        return 'docich.hanjuku_speedrun.hanjuku.' + module[len('docich.hanjuku.'):]
    if module.startswith('docich.hanjuku_'):
        return 'docich.hanjuku_speedrun.' + module[len('docich.'):]
    if module == 'brains.hanjuku':
        return 'brains.hanjuku_speedrun'
    if module.startswith('brains.hanjuku.'):
        return 'brains.hanjuku_speedrun.' + module[len('brains.hanjuku.'):]
    return None


def _source_module(path: str) -> str:
    if path.startswith('src/'):
        rel = path[len('src/'):]
    elif path.startswith('brains/'):
        rel = path
    else:
        raise ToolError(f'not a python source path: {path}')
    return rel[:-3].replace('/', '.')


def _source_package(path: str) -> str:
    module = _source_module(path)
    if path.endswith('/__init__.py'):
        return module
    return module.rpartition('.')[0]


def _build_module_map(paths: list[str]) -> dict[str, str]:
    module_map: dict[str, str] = {}
    modules = []
    for path in paths:
        if path.endswith('.py'):
            module = _source_module(path)
            modules.append(module)
            target = _target_module(module)
            if target:
                module_map[module] = target
    # Parent packages inside the copied tree need the same mapping so that
    # ``from docich import hanjuku`` and ``from docich.hanjuku import flows``
    # resolve to the copied package.
    for module in modules:
        parts = module.split('.')
        for index in range(2, len(parts)):
            package = '.'.join(parts[:index])
            if package in module_map:
                continue
            target = _target_module(package)
            if target:
                module_map[package] = target
    return module_map


