class _Source:
    """Character-offset view of a source file.

    ``ast`` reports UTF-8 byte column offsets; the file may contain Japanese
    text, so conversions have to use the encoded prefix.
    """

    def __init__(self, text: str):
        self.text = text
        self.lines = text.splitlines(keepends=True)
        self.line_starts: list[int] = []
        offset = 0
        for line in self.lines:
            self.line_starts.append(offset)
            offset += len(line)

    def _char_col(self, lineno: int, byte_col: int) -> int:
        line = self.lines[lineno - 1]
        return len(line.encode('utf-8')[:byte_col].decode('utf-8', 'replace'))

    def pos(self, lineno: int, byte_col: int) -> int:
        return self.line_starts[lineno - 1] + self._char_col(lineno, byte_col)

    def segment(self, node: ast.AST) -> str:
        start = self.pos(node.lineno, node.col_offset)
        end = self.pos(node.end_lineno, node.end_col_offset)
        return self.text[start:end]

    def line_prefix(self, node: ast.AST) -> str:
        line = self.lines[node.lineno - 1]
        return line[:self._char_col(node.lineno, node.col_offset)]


@dataclass(frozen=True)
class _Edit:
    start: int
    end: int
    text: str


def _apply_edits(source: str, edits: list[_Edit]) -> str:
    ordered = sorted(edits, key=lambda edit: (edit.start, edit.end))
    previous_end = -1
    for edit in ordered:
        if edit.start < previous_end:
            raise ToolError('internal error: overlapping source edits')
        previous_end = max(previous_end, edit.end)
    result = source
    for edit in reversed(ordered):
        result = result[:edit.start] + edit.text + result[edit.end:]
    return result


def _apply_name_rules(value: str) -> str:
    value = _GAME_RE.sub(GAME_SPEEDRUN, value)
    for old, new in SHARED_FILE_RENAMES.items():
        value = value.replace(old, new)
    return value


def _module_literal_target(value: str, module_map: dict[str, str]) -> str | None:
    """Exact module-name literal replacement (rule 2; never a prefix match)."""
    return module_map.get(value)


def _docstring_ids(tree: ast.AST) -> set[int]:
    ids: set[int] = set()
    for node in ast.walk(tree):
        if isinstance(node, (ast.Module, ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
            if not node.body:
                continue
            first = node.body[0]
            if (isinstance(first, ast.Expr)
                    and isinstance(first.value, ast.Constant)
                    and isinstance(first.value.value, str)):
                ids.add(id(first.value))
    return ids


def _fstring_constant_ids(tree: ast.AST) -> set[int]:
    ids: set[int] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.JoinedStr):
            for value in node.values:
                if isinstance(value, ast.Constant) and isinstance(value.value, str):
                    ids.add(id(value))
    return ids


_STRING_LITERAL_RE = re.compile(
    r'^([A-Za-z]*)(\"\"\"|\'\'\'|\"|\')(.*)\2$', re.S,
)


def _string_literal(value: str) -> str:
    """Fallback literal for a string that cannot be edited in place."""
    return repr(value)


def _string_literal_like(segment: str, value: str) -> str:
    """Build ``value`` as a literal using the original quoting when safe."""
    match = _STRING_LITERAL_RE.match(segment)
    if match:
        prefix, quote = match.group(1), match.group(2)
        if '\n' not in value and '\\' not in value and quote not in value:
            return f'{prefix}{quote}{value}{quote}'
    return _string_literal(value)


def _rewrite_strings(
    tree: ast.AST,
    view: _Source,
    path: str,
    edits: list[_Edit],
    diagnostics: list[Diagnostic],
    module_map: dict[str, str],
) -> None:
    docstrings = _docstring_ids(tree)
    fstring_constants = _fstring_constant_ids(tree)
    for node in ast.walk(tree):
        if not isinstance(node, ast.Constant) or not isinstance(node.value, str):
            continue
        if id(node) in docstrings:
            continue

        module_target = _module_literal_target(node.value, module_map)
        if module_target is not None:
            segment = view.segment(node)
            replacement = (module_target if id(node) in fstring_constants
                           else _string_literal_like(segment, module_target))
            edits.append(_Edit(
                view.pos(node.lineno, node.col_offset),
                view.pos(node.end_lineno, node.end_col_offset),
                replacement,
            ))
            continue

        new_value = _apply_name_rules(node.value)
        if new_value == node.value:
            continue
        segment = view.segment(node)
        new_segment = _apply_name_rules(segment)
        if new_segment != segment:
            edits.append(_Edit(
                view.pos(node.lineno, node.col_offset),
                view.pos(node.end_lineno, node.end_col_offset),
                new_segment,
            ))
            continue
        if id(node) in fstring_constants:
            diagnostics.append(Diagnostic(
                path, node.lineno,
                'string content needs an escaped rewrite; f-string segment was not changed',
            ))
            continue
        # The value is split over adjacent literals or uses an escape.  A
        # normal str literal can be replaced as a whole with repr(); the value
        # (not the original quoting) is what the copy has to preserve.
        edits.append(_Edit(
            view.pos(node.lineno, node.col_offset),
            view.pos(node.end_lineno, node.end_col_offset),
            _string_literal(new_value),
        ))


def _call_name(node: ast.AST) -> str | None:
    if isinstance(node, ast.Name):
        return node.id
    if isinstance(node, ast.Attribute):
        base = _call_name(node.value)
        return f'{base}.{node.attr}' if base else None
    return None


def _is_file_path(node: ast.AST) -> bool:
    if isinstance(node, ast.Name):
        return node.id == '__file__'
    if isinstance(node, ast.Call):
        name = _call_name(node.func)
        if name in {'Path', 'pathlib.Path', 'str', 'os.fspath', 'os.path.abspath',
                    'os.path.realpath'}:
            return bool(node.args) and _is_file_path(node.args[0])
        if isinstance(node.func, ast.Attribute) and node.func.attr in {
            'resolve', 'absolute', 'expanduser',
        }:
            return _is_file_path(node.func.value)
        return False
    if isinstance(node, ast.Attribute):
        if node.attr in {'parent', 'parents'}:
            return _is_file_path(node.value)
        return False
    if isinstance(node, ast.Subscript):
        return (
            isinstance(node.value, ast.Attribute)
            and node.value.attr == 'parents'
            and _is_file_path(node.value.value)
        )
    return False


def _parent_count(node: ast.AST) -> int:
    count = 0
    current = node
    while isinstance(current, ast.Attribute) and current.attr == 'parent':
        count += 1
        current = current.value
    return count


def _dirname_depth(node: ast.AST) -> int | None:
    """Number of nested ``os.path.dirname`` calls ending at a file path."""
    if isinstance(node, ast.Call):
        if _call_name(node.func) in {'os.path.dirname', 'dirname'} and len(node.args) == 1:
            inner = _dirname_depth(node.args[0])
            if inner is not None:
                return inner + 1
            if _is_file_path(node.args[0]):
                return 1
            return None
        if _is_file_path(node):
            return 0
    if _is_file_path(node):
        return 0
    return None


def _rewrite_brain_state_dir(
    tree: ast.AST,
    view: _Source,
    path: str,
    edits: list[_Edit],
) -> None:
    """Keep the optional external brain's ``run/brain/hanjuku`` state separate.

    This is a directory rather than one file name, so it cannot be expressed
    in :data:`SHARED_FILE_RENAMES`.  The only source of it in the copied set is
    ``brains/hanjuku/brain.py``; the default speedrun agent is the command bot,
    but a copied brain must not share state if an operator selects it.
    """
    if path != 'brains/hanjuku/brain.py':
        return
    for node in ast.walk(tree):
        if not isinstance(node, ast.BinOp) or not isinstance(node.op, ast.Div):
            continue
        right = node.right
        if not (isinstance(right, ast.Constant)
                and isinstance(right.value, str)
                and right.value == 'hanjuku'):
            continue
        components = []
        current: ast.AST | None = node
        while isinstance(current, ast.BinOp) and isinstance(current.op, ast.Div):
            components.append(current.right)
            current = current.left
        components.append(current)
        values = []
        for part in components:
            if isinstance(part, ast.Constant) and isinstance(part.value, str):
                values.append(part.value)
            elif isinstance(part, ast.Call):
                values.extend(
                    arg.value for arg in part.args
                    if isinstance(arg, ast.Constant) and isinstance(arg.value, str)
                )
        if 'run' in values and 'brain' in values:
            edits.append(_Edit(
                view.pos(right.lineno, right.col_offset),
                view.pos(right.end_lineno, right.end_col_offset),
                _string_literal_like(view.segment(right), 'hanjuku_speedrun'),
            ))


def _rewrite_paths(
    tree: ast.AST,
    view: _Source,
    path: str,
    edits: list[_Edit],
    diagnostics: list[Diagnostic],
) -> None:
    parent_map: dict[int, ast.AST] = {}
    for parent in ast.walk(tree):
        for child in ast.iter_child_nodes(parent):
            parent_map[id(child)] = parent

    for node in ast.walk(tree):
        if isinstance(node, ast.Subscript):
            value = node.value
            if (isinstance(value, ast.Attribute) and value.attr == 'parents'
                    and _is_file_path(value.value)):
                index = node.slice
                if (isinstance(index, ast.Constant) and type(index.value) is int
                        and index.value >= 0):
                    edits.append(_Edit(
                        view.pos(index.lineno, index.col_offset),
                        view.pos(index.end_lineno, index.end_col_offset),
                        str(index.value + 1),
                    ))
                else:
                    diagnostics.append(Diagnostic(
                        path, node.lineno,
                        'Path(__file__).parents[...] has a non-literal or negative index',
                    ))
                continue

        if isinstance(node, ast.Attribute) and node.attr == 'parent' and _is_file_path(node):
            count = _parent_count(node)
            if count < 2:
                continue
            parent = parent_map.get(id(node))
            if isinstance(parent, ast.Attribute) and parent.attr == 'parent':
                continue
            end = view.pos(node.end_lineno, node.end_col_offset)
            edits.append(_Edit(end, end, '.parent'))
            continue

        if isinstance(node, ast.Call):
            if _call_name(node.func) not in {'os.path.dirname', 'dirname'}:
                continue
            depth = _dirname_depth(node)
            if depth is None or depth < 2:
                continue
            parent = parent_map.get(id(node))
            if (isinstance(parent, ast.Call)
                    and _call_name(parent.func) in {'os.path.dirname', 'dirname'}
                    and len(parent.args) == 1 and parent.args[0] is node):
                continue
            start = view.pos(node.lineno, node.col_offset)
            end = view.pos(node.end_lineno, node.end_col_offset)
            segment = view.text[start:end]
            edits.append(_Edit(start, end, f'os.path.dirname({segment})'))


def _resolve_relative(module: str | None, level: int, package: str) -> str | None:
    if level == 0:
        return module or ''
    parts = package.split('.') if package else []
    remove = level - 1
    if remove >= len(parts):
        return None
    base = parts[:len(parts) - remove]
    if module:
        base.extend(module.split('.'))
    return '.'.join(base)


def _format_alias(name: str, asname: str | None) -> str:
    return f'{name} as {asname}' if asname else name


def _format_import_from(module: str, names: list[tuple[str, str | None]]) -> str:
    return f'from {module} import ' + ', '.join(_format_alias(*name) for name in names)


def _rewrite_import(
    node: ast.Import | ast.ImportFrom,
    package: str,
    module_map: dict[str, str],
    path: str,
) -> tuple[list[str] | None, str | None]:
    if isinstance(node, ast.Import):
        names = []
        changed = False
        for alias in node.names:
            target = module_map.get(alias.name, alias.name)
            if target != alias.name:
                changed = True
            names.append((target, alias.asname))
        if not changed:
            return None, None
        return ['import ' + ', '.join(_format_alias(*name) for name in names)], None

    absolute = _resolve_relative(node.module, node.level, package)
    if absolute is None:
        return None, (
            f'relative import level {node.level} goes above the package root'
        )

    # When the module itself is copied, every imported name lives in the copy.
    if absolute in module_map:
        names = [(alias.name, alias.asname) for alias in node.names]
        return [_format_import_from(module_map[absolute], names)], None

    # Otherwise a name may itself be a copied module (``from docich import
    # hanjuku_run``).  Split only when the target module really differs, and
    # keep the original order for side effects.
    groups: list[tuple[str, list[tuple[str, str | None]]]] = []
    changed = node.level != 0
    for alias in node.names:
        candidate = f'{absolute}.{alias.name}' if absolute else alias.name
        if candidate in module_map:
            target = module_map[candidate]
            target_module, _, target_name = target.rpartition('.')
            entry = (target_module, [(target_name, alias.asname)])
            changed = True
        else:
            entry = (absolute, [(alias.name, alias.asname)])
        if groups and groups[-1][0] == entry[0]:
            groups[-1][1].extend(entry[1])
        else:
            groups.append(entry)

    if not changed:
        return None, None
    return [_format_import_from(module, names) for module, names in groups], None


