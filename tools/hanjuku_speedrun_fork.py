def _build(source_ref: str, repo: Path) -> tuple[Generated, str]:
    sha = _resolve_commit(source_ref, repo)
    paths = _list_tree(sha, repo)
    source_paths = _select_source_paths(paths)
    if not source_paths:
        raise ToolError(f'no Hanjuku sources found at {sha}')

    module_map = _build_module_map(source_paths)
    files: dict[str, bytes] = {}
    diagnostics: list[Diagnostic] = []
    reviews: list[Diagnostic] = []

    for path in source_paths:
        data = _read_blob(sha, path, repo)
        target = _target_path(path)
        if path.endswith('.py'):
            text, file_diagnostics, file_reviews = _transform_python(
                path, data, sha, module_map,
            )
            diagnostics.extend(file_diagnostics)
            if path in SOURCE_PATCHES:
                text = _apply_source_patches(path, text)
            else:
                # An unresolved dynamic module name outside the patch table
                # would load the original's modules from the copy: fail.
                diagnostics.extend(file_reviews)
            files[target] = text.encode('utf-8')
        elif path == CONFIG_SOURCE:
            files[target] = _transform_config(data, sha)
        else:  # pragma: no cover - selection only returns known paths
            raise ToolError(f'unhandled source path: {path}')

    if SPEEDRUN_INIT_REL not in files:
        files[SPEEDRUN_INIT_REL] = _insert_header(
            SPEEDRUN_INIT_BODY, sha,
        ).encode('utf-8')

    file_hashes = {
        relative: hashlib.sha256(files[relative]).hexdigest()
        for relative in sorted(files)
    }
    fork = {
        'schema': 1,
        'source_commit': sha,
        'frozen': False,
        'files': file_hashes,
    }
    files[FORK_REL] = (json.dumps(
        fork, ensure_ascii=False, indent=2, sort_keys=True,
    ) + '\n').encode('utf-8')
    return Generated(files=files, diagnostics=diagnostics, reviews=reviews), sha


def _atomic_write(path: Path, data: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix=f'.{path.name}.', dir=str(path.parent))
    try:
        with os.fdopen(fd, 'wb') as stream:
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    except BaseException:
        try:
            os.unlink(temporary)
        except OSError:
            pass
        raise


def _read_fork(output_root: Path) -> dict | None:
    path = output_root / FORK_REL
    if not path.is_file():
        return None
    try:
        document = json.loads(path.read_text(encoding='utf-8'))
    except (OSError, ValueError) as exc:
        raise ToolError(f'{path}: cannot read FORK.json: {exc}') from exc
    if not isinstance(document, dict):
        raise ToolError(f'{path}: FORK.json is not an object')
    return document


def _report_diagnostics(diagnostics: list[Diagnostic], *, allow: bool) -> None:
    if not diagnostics:
        return
    label = 'warning' if allow else 'error'
    for item in diagnostics:
        print(f'{label}: {item.path}:{item.lineno}: {item.reason}', file=sys.stderr)
    if not allow:
        raise ToolError(
            f'{len(diagnostics)} unresolved rewrite(s); '
            'rerun with --allow-unresolved to keep them as warnings',
        )


def command_generate(args: argparse.Namespace) -> int:
    repo = _find_repo_root(args.repo)
    output_root = Path(args.output_root).resolve() if args.output_root else repo
    fork = _read_fork(output_root)
    if fork is not None and bool(fork.get('frozen')):
        if not args.force_unfreeze:
            raise ToolError(
                f'{output_root / FORK_REL} is frozen; '
                'use --force-unfreeze to regenerate',
            )

    generated, sha = _build(args.source, repo)
    _report_diagnostics(generated.diagnostics, allow=args.allow_unresolved)
    for review in generated.reviews:
        print(f'review: {review.path}:{review.lineno}: {review.reason}', file=sys.stderr)

    for relative in sorted(generated.files):
        if relative == FORK_REL:
            continue
        _atomic_write(output_root / relative, generated.files[relative])
    # The manifest is the commit point: write it only after every source file.
    _atomic_write(output_root / FORK_REL, generated.files[FORK_REL])
    print(f'generated {len(generated.files)} files from {sha}')
    return 0


def command_check(args: argparse.Namespace) -> int:
    repo = _find_repo_root(args.repo)
    output_root = Path(args.output_root).resolve() if args.output_root else repo
    fork = _read_fork(output_root)
    if fork is None:
        raise ToolError(f'{output_root / FORK_REL} not found')
    if bool(fork.get('frozen')):
        print('check: frozen; skipped')
        return 0

    source_ref = args.source or fork.get('source_commit')
    if not isinstance(source_ref, str) or not source_ref:
        raise ToolError('FORK.json has no source_commit and --source was not given')

    generated, sha = _build(source_ref, repo)
    _report_diagnostics(generated.diagnostics, allow=args.allow_unresolved)

    differences = []
    for relative in sorted(generated.files):
        path = output_root / relative
        try:
            actual = path.read_bytes()
        except OSError:
            differences.append(relative)
            continue
        if actual != generated.files[relative]:
            differences.append(relative)
    if differences:
        print(f'check: generated copy differs from {sha}:', file=sys.stderr)
        for relative in differences:
            print(f'  {relative}', file=sys.stderr)
        return 1
    print(f'check: OK ({len(generated.files)} files from {sha})')
    return 0


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--repo', help='repository root (default: current git worktree)')
    subparsers = parser.add_subparsers(dest='command', required=True)

    generate = subparsers.add_parser('generate', help='write the generated copy')
    generate.add_argument('--repo', default=argparse.SUPPRESS,
                          help='repository root (also accepted before the subcommand)')
    generate.add_argument('--source', default='HEAD', help='git ref (default: HEAD)')
    generate.add_argument('--output-root', help='write under this root (default: repository)')
    generate.add_argument('--force-unfreeze', action='store_true',
                          help='regenerate even when FORK.json is frozen')
    generate.add_argument('--allow-unresolved', action='store_true',
                          help='keep unresolved rewrites as warnings')
    generate.set_defaults(func=command_generate)

    check = subparsers.add_parser('check', help='compare the copy with a fresh build')
    check.add_argument('--repo', default=argparse.SUPPRESS,
                       help='repository root (also accepted before the subcommand)')
    check.add_argument('--source', help='git ref (default: FORK.json source_commit)')
    check.add_argument('--output-root', help='read the copy under this root (default: repository)')
    check.add_argument('--allow-unresolved', action='store_true',
                       help='keep unresolved rewrites as warnings')
    check.set_defaults(func=command_check)
    return parser


def main(argv: list[str] | None = None) -> int:
    parser = _parser()
    args = parser.parse_args(argv)
    try:
        return args.func(args)
    except ToolError as exc:
        print(f'error: {exc}', file=sys.stderr)
        return 2


if __name__ == '__main__':
    sys.exit(main())
