#!/usr/bin/env python3
"""Compile the labelled reference corpus into stdlib-only runtime data."""
import argparse
import base64
import hashlib
import json
from pathlib import Path
import zlib

ROOT = Path(__file__).resolve().parents[1]
CORPUS = ROOT / 'evals/hanjuku/castles'
OUTPUT = ROOT / 'src/docich/hanjuku/os_layer/castle_data.py'


def build() -> str:
    from PIL import Image

    manifest_bytes = (CORPUS / 'manifest.json').read_bytes()
    manifest = json.loads(manifest_bytes)
    groups, pixels = {}, []
    for record in manifest['classes']:
        for sample in record['samples']:
            path = CORPUS / sample['file']
            if hashlib.sha256(path.read_bytes()).hexdigest() != sample['png_sha256']:
                raise ValueError('corpus PNG checksum mismatch')
            with Image.open(path) as image:
                if image.mode != 'RGBA' or image.size != (48, 56):
                    raise ValueError('invalid reference dimensions or mode')
                rgba = image.tobytes()
            digest = hashlib.sha256(rgba).hexdigest()
            if digest != sample['rgba_sha256']:
                raise ValueError('corpus pixel checksum mismatch')
            # Own castles have five shared shapes. Their <=8/channel palette
            # variation is capture tolerance, not another chapter/level class.
            key = (record['owner'], record['level'], 0 if record['owner'] == 'own' else sample['theme'])
            if key in groups:
                group, original = groups[key]
                if (group[:2] != [record['owner'], record['level']]
                        or group[3] != sample['animated_flag_cells_xy']
                        or not all(abs(a - b) <= 8 for a, b in zip(original, rgba))):
                    raise ValueError('own castle chapter variation exceeds capture tolerance')
                group[2].append(sample['theme'])
            else:
                group = [record['owner'], record['level'], [sample['theme']], sample['animated_flag_cells_xy']]
                groups[key] = (group, rgba)
                pixels.append(rgba)
    labels = []
    for group, rgba in groups.values():
        flags = group[3]
        points = [(x, y, tuple(rgba[(y * 48 + x) * 4:(y * 48 + x) * 4 + 3]))
                  for y in range(56) for x in range(48)
                  if rgba[(y * 48 + x) * 4 + 3] and [x // 8, y // 8] not in flags]
        anchors = [points[0]]
        for i in range(1, 12):
            choices = points
            if i % 3 == 2 and anchors[-1][2] == anchors[-2][2]:
                choices = [p for p in points if p[2] != anchors[-1][2]]
            anchors.append(max(choices, key=lambda p: min(
                (p[0] - a[0]) ** 2 + (p[1] - a[1]) ** 2
                + (16 if p[2] != a[2] else 0) for a in anchors)))
        labels.append((group[0], group[1], tuple(group[2]), tuple(map(tuple, group[3])),
                       tuple((x, y) for x, y, _ in anchors)))
    encoded = base64.b85encode(zlib.compress(b''.join(pixels), 9)).decode('ascii')
    lines = '\n'.join(f'    {encoded[i:i+96]!r}' for i in range(0, len(encoded), 96))
    return ('"""Generated by tools/hanjuku_compile_castles.py; do not edit by hand.\n'
            '30 labelled PNG references -> 5 shared own + 15 enemy shapes.\n"""\n'
            f'CORPUS_SHA256 = {hashlib.sha256(manifest_bytes).hexdigest()!r}\n'
            'LABELS = (\n' + ''.join(f'    {label!r},\n' for label in labels) + ')\n'
            f'RGBA_B85 = (\n{lines}\n)\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source = build()
    if args.check:
        if OUTPUT.read_text() != source:
            parser.exit(1, 'castle runtime data is stale\n')
        print('castle runtime data matches all 30 references')
    else:
        OUTPUT.write_text(source)


if __name__ == '__main__':
    main()
