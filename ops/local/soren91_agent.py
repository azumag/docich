#!/usr/bin/env python3
"""GUI-session launchd service for the existing Soren91 macOS renderer agent.

The secret is read only at launch/status, never put in argv, plist, or output.
This owns the local HTTP agent only; it never requests a game start or stop.

The launchd job runs a dedicated ``Soren91Renderer.app`` bundle instead of the
interpreter directly. macOS TCC binds a Screen Recording grant to the process
that OS attribution reports as responsible; a bare ``node``/``python3`` parent
makes every process using that interpreter share the grant. A LaunchServices
app bundle with a compiled Mach-O launcher keeps the grant on
``com.docich.soren91-renderer``, and its children (python -> node -> capture
helper) inherit that identity. The bundle id, launcher, and signing steps are
therefore part of the security boundary: do not launch ``service.py run``
directly for a corner.
"""
import argparse
import ipaddress
import json
import os
from pathlib import Path
import plistlib
import shutil
import socket
import stat
import subprocess
import sys
import tempfile
import urllib.request

LABEL = "com.docich.soren91-agent"
APP_BUNDLE_ID = "com.docich.soren91-renderer"
APP_NAME = "Soren91Renderer"
CLANG = "/usr/bin/clang"
CODESIGN = "/usr/bin/codesign"
OPEN = "/usr/bin/open"
FIELDS = {"repo", "node", "ffmpeg", "token_file", "host", "port"}

LAUNCHER_SOURCE = """\
/* Generated by ops/local/soren91_agent.py. Do not edit in the bundle.
 *
 * The Screen Recording grant is scoped to this app bundle, so the launcher
 * must stay the responsible process: it forks the python service (which then
 * execs node) and waits instead of exec'ing anything itself.
 */
#include <errno.h>
#include <signal.h>
#include <sys/wait.h>
#include <unistd.h>

static volatile sig_atomic_t child_pid = 0;

static void forward_term(int signal_number) {
    if (child_pid > 0) kill((pid_t)child_pid, SIGTERM);
}

int main(void) {
    struct sigaction action;
    action.sa_handler = forward_term;
    sigemptyset(&action.sa_mask);
    action.sa_flags = 0;
    sigaction(SIGTERM, &action, (struct sigaction *)0);
    sigaction(SIGINT, &action, (struct sigaction *)0);
    pid_t pid = fork();
    if (pid == 0) {
        execl(%(python)s, "python3", %(script)s, "run", "--config", %(config)s,
              (char *)0);
        _exit(127);
    }
    if (pid < 0) return 127;
    child_pid = (sig_atomic_t)pid;
    int status = 0;
    while (waitpid(pid, &status, 0) < 0) {
        if (errno != EINTR) return 127;
    }
    child_pid = 0;
    if (WIFEXITED(status)) return WEXITSTATUS(status);
    if (WIFSIGNALED(status)) return 128 + WTERMSIG(status);
    return 127;
}
"""


def read_token(path):
    # O_NOFOLLOW closes the symlink race; reject permissive/foreign files.
    fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    with os.fdopen(fd, "rb") as stream:
        info = os.fstat(stream.fileno())
        if (not stat.S_ISREG(info.st_mode) or info.st_uid != os.getuid()
                or stat.S_IMODE(info.st_mode) & 0o077):
            raise ValueError("credential-file-permissions")
        data = stream.read(4097)
    token = data.decode("ascii").strip()
    if not 24 <= len(token) <= 4096 or any(not 33 <= ord(c) <= 126 for c in token):
        raise ValueError("credential-file-shape")
    return token


def validate(config):
    if not isinstance(config, dict) or set(config) != FIELDS:
        raise ValueError("configuration-shape")
    host = ipaddress.ip_address(config["host"])
    if host.version != 4 or host not in ipaddress.ip_network("100.64.0.0/10"):
        raise ValueError("tailscale-address-required")
    if type(config["port"]) is not int or not 1024 <= config["port"] <= 65535:
        raise ValueError("configuration-port")
    for key in ("repo", "node", "ffmpeg", "token_file"):
        if not isinstance(config[key], str) or not Path(config[key]).is_absolute():
            raise ValueError("absolute-path-required")
    if not (Path(config["repo"]) / "tools/soren91_local_agent.mjs").is_file():
        raise ValueError("agent-script-missing")
    for key in ("node", "ffmpeg"):
        if not Path(config[key]).is_file() or not os.access(config[key], os.X_OK):
            raise ValueError("executable-missing")
    return config


def environment(config, inherited=None):
    validate(config)
    inherited = os.environ if inherited is None else inherited
    env = {k: inherited[k] for k in ("HOME", "USER", "LOGNAME", "TMPDIR", "LANG")
           if k in inherited}
    # Do not inherit stale SOREN91_* overrides from an interactive shell.
    env.update({
        "PATH": "/opt/homebrew/bin:/usr/bin:/bin:/usr/sbin:/sbin",
        "SOREN91_LOCAL_AGENT_HOST": config["host"],
        "SOREN91_LOCAL_AGENT_PORT": str(config["port"]),
        "SOREN91_LOCAL_AGENT_TOKEN": read_token(config["token_file"]),
        "SOREN91_LOCAL_SESSION_MODE": "cdp-host",
        "SOREN91_CDP_BIND_IP": config["host"],
        "SOREN91_LOCAL_FFMPEG_BIN": config["ffmpeg"],
        "SOREN91_CDP_HOST_SESSION_SEC": "2400",
        # Game-audio gain applied on the Mac ffmpeg audio chain (volume=<gain>).
        # The game's native tap level reads quiet next to the comment voice;
        # owner asked to lift it modestly (2026-09-29). Kept explicit here (not
        # inherited) so a shell override can never change the on-air mix.
        "SOREN91_LOCAL_AUDIO_GAIN": "1.4",
    })
    return env


def _c_string(value):
    """Render an absolute path as an ASCII-only C string literal."""
    raw = str(value)
    if not raw or "\x00" in raw or not os.path.isabs(raw):
        raise ValueError("invalid-launcher-path")
    out = ['"']
    for char in raw:
        if char in ('"', "\\"):
            out.append("\\" + char)
        elif 32 <= ord(char) < 127:
            out.append(char)
        else:
            for byte in char.encode("utf-8"):
                out.append("\\%03o" % byte)
    out.append('"')
    return "".join(out)


def launcher_source(python, script, config):
    return LAUNCHER_SOURCE % {
        "python": _c_string(python),
        "script": _c_string(script),
        "config": _c_string(config),
    }


def app_info_plist():
    return {
        "CFBundleIdentifier": APP_BUNDLE_ID,
        "CFBundleExecutable": APP_NAME,
        "CFBundleName": "Soren91 Renderer",
        "CFBundleDisplayName": "Soren91 Renderer",
        "CFBundlePackageType": "APPL",
        "CFBundleVersion": "1",
        "CFBundleShortVersionString": "1.0",
        # No Dock icon, no activation: the app only owns the renderer agent.
        "LSBackgroundOnly": True,
        "LSMinimumSystemVersion": "14.0",
    }


def app_bundle(root):
    return Path(root) / (APP_NAME + ".app")


def build_app(root, python, script, config):
    """Create, compile, and ad-hoc sign the renderer app bundle.

    The bundle identifier is the Screen Recording grant target, so this fails
    closed when the signature identity does not match.
    """
    if sys.platform != "darwin":
        raise ValueError("macos-required")
    for binary in (CLANG, CODESIGN):
        if not Path(binary).is_file():
            raise ValueError("toolchain-missing")
    if str(python).startswith("/Volumes/"):
        # A LaunchServices app without the Removable Volumes grant can block on
        # an interpreter stored on an external volume (observed as a hang).
        raise ValueError("python-on-removable-volume")
    app = app_bundle(root)
    macos = app / "Contents/MacOS"
    (app / "Contents/Resources").mkdir(parents=True, exist_ok=True)
    macos.mkdir(parents=True, exist_ok=True)
    (app / "Contents/Info.plist").write_bytes(plistlib.dumps(app_info_plist()))
    binary = macos / APP_NAME
    with tempfile.TemporaryDirectory(prefix="soren91-launcher-") as work:
        source = Path(work) / "launcher.c"
        source.write_text(launcher_source(python, script, config))
        subprocess.run(
            [CLANG, "-O2", "-Wall", "-Wextra", "-o", str(binary), str(source)],
            check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
        )
    binary.chmod(0o755)
    subprocess.run(
        [CODESIGN, "--force", "--sign", "-", "--identifier", APP_BUNDLE_ID, str(app)],
        check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
    )
    detail = subprocess.run(
        [CODESIGN, "-dv", "--verbose=4", str(app)],
        check=True, capture_output=True, text=True,
    )
    if ("Identifier=" + APP_BUNDLE_ID) not in (detail.stdout + detail.stderr):
        raise ValueError("app-signature-identity")
    subprocess.run(
        [CODESIGN, "--verify", "--strict", str(app)],
        check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
    )
    return app


def service_plist(app):
    # LaunchServices owns the app identity (and therefore the TCC grant);
    # -W keeps the launchd job's lifetime tied to the app's.
    return {
        "Label": LABEL,
        "ProgramArguments": [OPEN, "-W", "-n", str(app)],
        "LimitLoadToSessionType": "Aqua",
        "RunAtLoad": True,
        "KeepAlive": True,
        "ThrottleInterval": 30,
        "ExitTimeOut": 20,
        "ProcessType": "Interactive",
        # launchd retains the exit status. Query authenticated status for health;
        # child logs may contain URLs or arbitrary output, so never forward them.
        "StandardOutPath": "/dev/null",
        "StandardErrorPath": "/dev/null",
    }


def paths(home):
    root = home / "Library/Application Support/docich/soren91-agent"
    return root, home / "Library/LaunchAgents" / (LABEL + ".plist")


def install(config):
    if sys.platform != "darwin":
        raise ValueError("macos-required")
    validate(config)
    read_token(config["token_file"])
    domain = "gui/" + str(os.getuid())
    subprocess.run(["launchctl", "print", domain], check=True, stdout=subprocess.DEVNULL,
                   stderr=subprocess.DEVNULL)
    loaded = subprocess.run(["launchctl", "print", domain + "/" + LABEL],
                            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    if loaded.returncode == 0:
        raise ValueError("service-already-loaded")
    # Never replace a manually running agent (or another listener) blindly.
    with socket.socket() as probe:
        probe.settimeout(2)
        if probe.connect_ex((config["host"], config["port"])) == 0:
            raise ValueError("agent-port-occupied")
    root, plist_path = paths(Path.home())
    if root.exists() or plist_path.exists():
        raise ValueError("installation-already-exists")
    root.mkdir(parents=True, mode=0o700)
    try:
        script = root / "service.py"
        shutil.copyfile(Path(__file__), script)
        script.chmod(0o700)
        config_path = root / "config.json"
        config_path.write_text(json.dumps(config, sort_keys=True) + "\n")
        config_path.chmod(0o600)
        app = build_app(root, Path(sys.executable).resolve(), script, config_path)
        plist_path.parent.mkdir(parents=True, exist_ok=True)
        plist_path.write_bytes(plistlib.dumps(service_plist(app)))
        plist_path.chmod(0o600)
        subprocess.run(["launchctl", "bootstrap", domain, str(plist_path)], check=True,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    except Exception:
        # install() refuses pre-existing installations, so this tree was
        # created here and a partial build cannot discard earlier state.
        shutil.rmtree(root, ignore_errors=True)
        try:
            plist_path.unlink()
        except OSError:
            pass
        raise
    print(json.dumps({"status": "installed", "label": LABEL,
                      "app": APP_NAME, "bundle_id": APP_BUNDLE_ID}))


def status(config):
    validate(config)
    request = urllib.request.Request(
        "http://{}:{}/v1/status".format(config["host"], config["port"]),
        headers={"Authorization": "Bearer " + read_token(config["token_file"])})
    # The private Tailscale request must not traverse an inherited HTTP proxy.
    opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))
    with opener.open(request, timeout=5) as response:
        value = json.loads(response.read(16385))
    if (value.get("ok") is not True or value.get("backend") != "local-macos"
            or value.get("mode") != "cdp-host" or type(value.get("running")) is not bool):
        raise ValueError("unexpected-agent-status")
    # Fixed projection: never print arbitrary responses, lastExit or URL.
    return {"status": "healthy", "backend": "local-macos", "mode": "cdp-host",
            "renderer_running": value["running"]}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("operation", choices=("install", "run", "status"))
    parser.add_argument("--config", type=Path, required=True,
                        help="non-secret JSON: repo, node, ffmpeg, token_file, host, port")
    args = parser.parse_args()
    try:
        config = validate(json.loads(args.config.read_text()))
        if args.operation == "install":
            install(config)
        elif args.operation == "status":
            print(json.dumps(status(config)))
        else:
            if sys.platform != "darwin":
                raise ValueError("macos-required")
            env = environment(config)
            os.chdir(config["repo"])
            # Exec, rather than detach, makes the launcher's child own the
            # agent PID/group under the app bundle identity.
            os.execve(config["node"], [config["node"], "tools/soren91_local_agent.mjs"], env)
        return 0
    except Exception:
        # Neither credential values nor arbitrary exception text reach logs.
        print(json.dumps({"status": "failed", "operation": args.operation}), file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
