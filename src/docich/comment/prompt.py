# GNU envsubst identifiers are ASCII; a Unicode \w would swallow "$nameの".
_VAR_RE = re.compile(r"\$\{([A-Za-z_][A-Za-z0-9_]*)\}|\$([A-Za-z_][A-Za-z0-9_]*)")


def asset(name: str) -> str:
    return (PROMPTS_DIR / name).read_text(encoding="utf-8")


def envsubst(template: str, names, values) -> str:
    """``envsubst 'NAMES'``: replace only the listed ``$NAME``/``${NAME}``, once.

    Unlisted references stay verbatim; a listed name without a value becomes
    empty (an unset variable); substituted values are never re-expanded.
    """
    allowed = frozenset(names)

    def replace(match):
        name = match.group(1) or match.group(2)
        return values.get(name, "") if name in allowed else match.group(0)
    return _VAR_RE.sub(replace, template)


def mode_assets(mode: str) -> dict[str, str]:
    """Persona / UI memo / channel intro / length policy of the host mode.

    Like the legacy ``$(cat file)``, trailing newlines are dropped.
    """
    if mode not in MODES:
        raise ValueError("unknown_mode")
    return {
        "_comment_persona": asset(f"comment_persona_{mode}.md").rstrip("\n"),
        "_comment_ui_memo": asset(f"comment_ui_memo_{mode}.md").rstrip("\n"),
        "_comment_channel_intro": asset(f"comment_channel_intro_{mode}.md").rstrip("\n"),
        "_comment_length_policy": asset("comment_length_policy_soren91.md") if mode == "soren91" else "",
    }


def time_period(hour: int) -> str:
    if 5 <= hour < 9:
        return "朝"
    if 9 <= hour < 12:
        return "午前"
    if 12 <= hour < 17:
        return "午後"
    if 17 <= hour < 21:
        return "夕方"
    if hour >= 21 or hour < 2:
        return "夜"
    return "未明"


