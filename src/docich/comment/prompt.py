def _bad_context_line(line: str) -> bool:
    stripped = line.strip()
    if not stripped:
        return False
    if re.match(r"^(error|warning)\s*:", stripped, re.I):
        return True
    if re.match(r"^[✗✕×].*\b(read|glob|grep|ls|edit|write|multiedit)\b.*\bfailed\b", stripped, re.I):
        return True
    if re.match(r"^[✱→►▸]\s*(read|glob|grep|ls|edit|write|multiedit)\b", stripped, re.I):
        return True
    return any(pattern.search(stripped) for pattern in _ERROR_PATTERNS)


def sanitize_context(text: str) -> str:
    """Drop provider error / tool-log lines and blank lines; empty -> "（なし）"."""
    kept = [raw.rstrip() for raw in text.splitlines() if not _bad_context_line(raw)]
    joined = "\n".join(line for line in kept if line.strip()).strip()
    return joined if joined else NONE


def with_defaults(ctx: dict) -> dict:
    """The legacy "Pre-resolve defaults for envsubst" step (empty/unset -> placeholder)."""
    out = dict(ctx)

    def default(name, value):
        return out.get(name) or value
    for name in ("comment_batch_context", "strategy_advice_candidates", "comment_advice_candidates",
                 "codex_advice_candidates", "comment_advice_context"):
        out[name] = default(name, NONE)
    for name, value in (("previous_comments_context", NONE), ("recent_spoken_comment_context", NONE),
                        ("viewer_memory_context", "（該当する投稿者別メモなし）"),
                        ("comment_followup_hints", NONE)):
        out[name] = sanitize_context(default(name, value))
    out["celebration_history_context"] = default("celebration_history_context", NONE)
    out["comment_thumbnail_ocr_context"] = sanitize_context(default("comment_thumbnail_ocr_context", NONE))
    out["game_state_context"] = sanitize_context(default("game_state_context", "（取得失敗）"))
    out["comment_ops_context"] = sanitize_context(default("comment_ops_context", "（取得失敗）"))
    return out


def dominant_category(rows) -> str | None:
    """>80% share (or the only category) wins, otherwise "mixed"; None when unusable."""
    if not isinstance(rows, list) or not rows:
        return None
    counts: dict[str, int] = {}
    try:
        for item in rows:
            category = item.get("category", "chitchat")
            counts[category] = counts.get(category, 0) + 1
    except (AttributeError, TypeError):
        return None  # the legacy inline script exits 1
    dominant = max(counts, key=counts.get)
    if counts[dominant] / len(rows) > 0.8 or len(counts) == 1:
        return dominant
    return "mixed"


def english_count(rows) -> int:
    return sum(1 for row in rows if isinstance(row, dict) and row.get("is_english") is True) \
        if isinstance(rows, list) else 0


def format_classifications(rows, batch_lines) -> str:
    """``[i] user: comment -> category -> english|japanese/other`` per classified line.

    Malformed input yields "" as a whole, like the legacy script whose failure
    was swallowed (``2>/dev/null``).
    """
    try:
        return _format_classifications(rows, batch_lines)
    except (AttributeError, TypeError):
        return ""


def _format_classifications(rows, batch_lines) -> str:
    source = [line for line in batch_lines if line.strip()]
    out = []
    for item in rows:
        try:
            idx = int(item.get("index", 0))
        except Exception:
            idx = 0
        if 1 <= idx <= len(source):
            raw = source[idx - 1]
            user, comment = raw.split(": ", 1) if ": " in raw else ("", raw)
        else:
            user, comment = "", ""
        category = item.get("category", "chitchat")
        english = "english" if item.get("is_english") is True else "japanese/other"
        if comment:
            out.append(f"[{idx}] {user}: {comment} -> {category} -> {english}")
    return "\n".join(out)


_GACHA_COUNT_RE = re.compile(r"(\d+)\s*種中\s*(\d+)\s*種所持")


def _gacha_user(line: str) -> str:
    s = line.strip()
    if ": " in s:
        head, rest = s.split(": ", 1)
        m = re.match(r"\s*@?([^\s　:]+)\s*が", rest)
        if m:
            return m.group(1).lstrip("@")
        h = head.strip().lstrip("@")
        if h and not h.startswith("["):
            return h
        s = rest.strip()
    m = re.match(r"\s*@?([^\s　:]+)\s*が", s)
    return m.group(1).lstrip("@") if m else ""


def gacha_completion_note(comments_block: str, list_file: Path) -> str:
    """Celebrate a full card-set completion once per viewer; records first completions."""
    if not comments_block:
        return ""
    known: dict[str, str] = {}
    try:
        with open(list_file, encoding="utf-8", errors="ignore") as stream:
            for line in stream:
                name = line.strip()
                if name:
                    known.setdefault(name.lower(), name)
    except FileNotFoundError:
        pass
    already, newly, newly_keys = [], [], set()
    for raw in comments_block.splitlines():
        line = raw.strip()
        if not line:
            continue
        m = _GACHA_COUNT_RE.search(line)
        if not m:
            continue
        total, owned = int(m.group(1)), int(m.group(2))
        if total <= 0 or owned < total:
            continue
        user = _gacha_user(line)
        if not user:
            continue
        key = user.lower()
        if key in known:
            if known[key] not in already:
                already.append(known[key])
            continue
        if key in newly_keys:
            continue
        newly_keys.add(key)
        newly.append(user)
    if newly:
        try:
            Path(list_file).parent.mkdir(parents=True, exist_ok=True)
            with open(list_file, "a", encoding="utf-8") as stream:
                for user in newly:
                    stream.write(user + "\n")
        except OSError:
            pass
    out = []
    if already:
        out.append("次のユーザーは過去に全種コンプリート達成済みで、既に何度も祝福しています: " + "、".join(already) + "。")
        out.append("このユーザーにはコンプリート・全種制覇・制覇・112種制覇といった達成自体には一切触れず、今回引いたカードそのものの話だけをしてください。")
    if newly:
        out.append("次のユーザーは今回が初のコンプリート達成です: " + "、".join(newly) + "。一度だけ達成を祝ってください。")
    return "\n".join(out)


def category_template(category: str) -> str:
    template = {"game_question": "game", "game_status": "game",
                "strategy_advice": "default", "comment_advice": "default", "general_question": "default",
                "subscription": "default", "stream_goal": "default", "bits": "default",
                "other": "default"}.get(category, category)
    path = PROMPTS_DIR / f"comment_response_{template}.md"
    return path.name if path.is_file() else "comment_response_default.md"


def build_prompt(category: str | None, ctx: dict, *, comments_block: str, classifications: str,
                 gacha_list_file: Path) -> str:
    """The base prompt: category template, or ``comment_template.md`` for mixed/unknown."""
    if category and category != "mixed":
        note = gacha_completion_note(comments_block, gacha_list_file) if category == "card_gacha" else ""
        values = {**ctx, "CATEGORY_COMMENTS": comments_block, "COMMENT_CLASSIFICATIONS": classifications,
                  "twitch_comments_for_prompt": comments_block, "gacha_completion_note": note or NO_GACHA_NOTE}
        return envsubst(asset(category_template(category)), CATEGORY_TEMPLATE_VARS, values)
    return envsubst(asset("comment_template.md"), MIXED_TEMPLATE_VARS, ctx)


def with_reply_contract(prompt: str) -> str:
    """Append the output/factuality contract, the speech vocabulary rule, and the
    viewer-address / card-burst contract.

    The last block is what production actually appends: soviet_now's
    ``comment_runtime_policy.sh`` wraps ``_append_comment_reply_contract``
    after ``comment.sh`` is loaded.
    """
    return (prompt + asset("comment_reply_contract.md") + "\n" + asset("speech_vocabulary_rule.md")
            + asset("comment_reply_policy_contract.md"))


def retry_prompt(prompt: str, mode: str) -> str:
    """Attempt >1: the legacy regeneration addendum (+ the mode's retry length policy)."""
    out = prompt + asset("comment_retry_addendum.md")
    if mode == "soren91":
        out += asset("comment_retry_length_policy_soren91.md") + "\n"
    return out


def gacha_list_file(env=None) -> Path:
    env = os.environ if env is None else env
    return Path(env.get("GACHA_COMPLETED_USERS_FILE")
                or f"{env.get('TMP_HISTORY_DIR') or 'tmp/history'}/gacha_completed_users.txt")


